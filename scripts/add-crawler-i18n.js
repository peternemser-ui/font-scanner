// Deep merge helper
function deepMerge(target, source) {
  for (const key of Object.keys(source)) {
    if (source[key] && typeof source[key] === 'object' && !Array.isArray(source[key])) {
      if (!target[key]) target[key] = {};
      deepMerge(target[key], source[key]);
    } else if (target[key] === undefined) {
      target[key] = source[key];
    }
  }
  return target;
}

const langFiles = ['en', 'ja', 'zh', 'de', 'es', 'fr', 'pt', 'ru'];

for (const lang of langFiles) {
  const filePath = path.join('src/public/i18n', `${lang}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  if (!data.reports) data.reports = {};
  if (!data.reports.crawler) data.reports.crawler = {};

  const langTranslations = translations[lang] || translations.en;
  deepMerge(data.reports.crawler, langTranslations);

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(`Updated ${lang}.json - reports.crawler now has ${Object.keys(data.reports.crawler).length} top-level keys`);
}

