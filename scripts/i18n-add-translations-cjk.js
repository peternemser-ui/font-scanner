/**
 * i18n-add-translations-cjk.js
 *
 * Adds comprehensive Japanese (ja) and Chinese Simplified (zh) translations
 * for CJK locale files. Uses deep-merge so existing keys are never overwritten.
 *
 * Usage:  node scripts/i18n-add-translations-cjk.js
 */

const fs = require('fs');
const path = require('path');
const I18N_DIR = path.join(__dirname, '..', 'src', 'public', 'i18n');

function deepMerge(target, source) {
  for (const key of Object.keys(source)) {
    if (source[key] && typeof source[key] === 'object' && !Array.isArray(source[key])) {
      if (!target[key]) target[key] = {};
      deepMerge(target[key], source[key]);
    } else if (!(key in target)) {  // Never overwrite existing
      target[key] = source[key];
    }
  }
  return target;
}

function applyTranslations(locale, translations) {
  const filePath = path.join(I18N_DIR, `${locale}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  deepMerge(data, translations);
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(`Updated ${locale}.json`);
}

