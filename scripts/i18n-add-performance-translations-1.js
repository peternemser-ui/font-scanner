// APPLY: Merge translations into each language file
// ============================================================

function applyTranslations() {
  const langs = ['de', 'es', 'fr', 'ja', 'pt', 'zh', 'ru'];

  for (const lang of langs) {
    const filePath = path.join(i18nDir, lang + '.json');
    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

    if (!data.reports) data.reports = {};

    const langTranslations = translations[lang] || {};
    let addedCount = 0;

    // Build a nested object from flat keys
    const toMerge = {};
    for (const [flatKey, value] of Object.entries(langTranslations)) {
      setNestedKey(toMerge, flatKey, value);
      addedCount++;
    }

    // Deep merge into reports section
    deepMerge(data.reports, toMerge);

    // Write back
    fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
    console.log(`${lang}.json: added/updated ${addedCount} performance translations`);
  }

  // Verify
  console.log('\n=== Post-merge verification ===');
  const en = JSON.parse(fs.readFileSync(path.join(i18nDir, 'en.json'), 'utf8'));
  const enPerf = flattenKeys((en.reports && en.reports.performance) || {}, 'performance');
  const enPerfKeys = Object.keys(enPerf);

  for (const lang of langs) {
    const data = JSON.parse(fs.readFileSync(path.join(i18nDir, lang + '.json'), 'utf8'));
    const langPerf = flattenKeys((data.reports && data.reports.performance) || {}, 'performance');
    const langSet = new Set(Object.keys(langPerf));
    const missing = enPerfKeys.filter(k => !langSet.has(k));
    console.log(`${lang}: ${Object.keys(langPerf).length}/${enPerfKeys.length} performance keys (${missing.length} still missing)`);
  }
}

applyTranslations();
