function flattenKeys(obj, prefix) {
  prefix = prefix || '';
  let result = {};
  for (const k of Object.keys(obj)) {
    const key = prefix ? prefix + '.' + k : k;
    if (typeof obj[k] === 'object' && obj[k] !== null) Object.assign(result, flattenKeys(obj[k], key));
    else result[key] = obj[k];
  }
  return result;
}
